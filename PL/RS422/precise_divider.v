// 功能：使用 32 bit 相位累加器生成 UART 的 16 倍波特率使能脉冲；该脉冲不是独立时钟。
// ============================================================================
`timescale 1ns / 1ps

// =============================================================================
// 模块: precise_divider
// 功能: 使用 32 bit 相位累加方式从 100 MHz 产生 UART 16 倍过采样使能脉冲。
// 说明: divide_clken 是单拍时钟使能，不作为独立时钟使用；DEVIDE_CNT 决定波特率。
// =============================================================================

/***********************************************************************
    fc  : Refrence clock = 100MHz = 100 * 10^6
    fo  : Output clock
    K   : Counter Step (计数器初始位数)
    fo  = fc*[K/(2^32)] (fo = 需要产生的时钟)
    K   = fo*(2^32)/fc = fo*(2^32)/(100 * 10^6) = 42.94967296 * fo
***********************************************************************/
// 实现一个基于累加器的精确分频器，常用于产生UART通信等场景所需的特定频率时钟
module precise_divider #(
    // DEVIDE_CNT = 42.94967296 * fo
    parameter DEVIDE_CNT = 32'd81037118  // 115200bps * 16
)(
    // 全局时钟
    input wire clk,           // 100MHz
    // 用户接口
    output wire divide_clk,
    output wire divide_clken
);

// ==================================================
// RTL1: 精确分数分频计算 - 修复变量类型
// ==================================================
reg [31:0] cnt = 0;
always @(posedge clk) begin
    cnt <= cnt + DEVIDE_CNT;
end

// ==================================================
// RTL2: 等分频时钟生成 - 修复变量类型
// ==================================================
reg cnt_equal = 0;
always @(posedge clk) begin
    if (cnt < 32'h7FFF_FFFF)
        cnt_equal <= 0;
    else
        cnt_equal <= 1;
end

// ==================================================
// RTL3: 生成时钟使能信号 - 修复变量类型
// ==================================================
reg cnt_equal_r = 0;
always @(posedge clk) begin
    cnt_equal_r <= cnt_equal;
end

// 输出分配
assign divide_clken = (~cnt_equal_r & cnt_equal) ? 1'b1 : 1'b0;
assign divide_clk = cnt_equal_r;

endmodule
