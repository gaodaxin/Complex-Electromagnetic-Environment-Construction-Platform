`timescale 1ns / 1ps

// =============================================================================
// 模块: da_sig_pm_biphase
// 功能: BPSK 相位映射，按码元最低位输出 0 或 π 的 32 bit 周相位字。
// =============================================================================

module da_sig_pm_biphase (

    input  wire [15:0] chip,             // 码元序号 m
    output wire [31:0] phi               // 相位字：0 或 π（0x8000_0000）

);

assign phi = {chip[0], 31'd0};           // 取码元 LSB：1 则相位 MSB=1 即加 π，否则为 0

endmodule
