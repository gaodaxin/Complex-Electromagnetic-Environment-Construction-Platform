`timescale 1ns / 1ps

// =============================================================================
// 模块: da_sig_cw
// 功能: CW 调制支路。CW 不产生附加频偏，固定输出 F_mod=0。
// 说明: 独立保留该模块，使 da_sig_wave 的各调制类型具有一致接口。
// =============================================================================

module da_sig_cw (

    output wire signed [31:0] fm_mod,    // 当前频偏，恒 0
    output wire signed [31:0] fm_next    // 预览频偏，恒 0
);

// CW / 调相载波不需要 FM 频偏
// 瞬时频率就是 carrier：F_inst = carrier + 0

assign fm_mod  = 32'sd0;                 // 当前 F_mod=0
assign fm_next = 32'sd0;                 // 下一拍同样为 0

endmodule
