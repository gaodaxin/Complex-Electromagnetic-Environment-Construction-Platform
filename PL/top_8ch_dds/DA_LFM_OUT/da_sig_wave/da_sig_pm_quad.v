`timescale 1ns / 1ps

// =============================================================================
// 模块: da_sig_pm_quad
// 功能: QPSK 相位映射，按码元低两位输出 0、π/2、π 或 3π/2。
// =============================================================================

module da_sig_pm_quad (

    input  wire [15:0] chip,             // 码元序号 m
    output wire [31:0] phi               // 相位字：m·π/2，由低 2 bit 映射

);

assign phi = {chip[1:0], 30'd0};         // 00→0，01→π/2，10→π，11→3π/2

endmodule
