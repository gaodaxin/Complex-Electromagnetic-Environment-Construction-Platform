// 功能：迭代无符号除法器，支持整数商和左移 32 bit 的定点比例运算，供配置、扫描与 PRI 抖动使用。
// ============================================================================
`timescale 1ns / 1ps

// =============================================================================
// 模块名称：da_sig_div_u
//
// 功能：
//   无符号整数除法器，输出 32 bit 商。
//   不直接使用 Verilog 的 "/" 运算符，而是采用“恢复除法”算法逐 bit 求商。
//
//   可以理解成 FPGA 版的“二进制竖式除法”：
//
//       1. 从被除数中取下一位
//       2. 拼到当前余数 rem 后面
//       3. 判断新的余数是否 >= divisor
//       4. 如果够减：
//              rem = rem - divisor
//              当前商位 = 1
//          如果不够减：
//              rem 保持
//              当前商位 = 0
//       5. 重复 32 次，得到 32 bit 商
//
// -----------------------------------------------------------------------------
// 两种工作模式：
//
// 1）shl32 = 0
//
//      quot = floor(dividend[31:0] / divisor)
//
//   只使用 dividend 的低 32 bit。
//   dividend[31:0] 会装入 acc，然后每一轮从 acc[31] 取出一个 bit。
//
//   例如：
//      dividend = 13
//      divisor  = 3
//
//      13 = 1101b
//       3 = 0011b
//
//      最终：
//      quot = 4
//
// -----------------------------------------------------------------------------
// 2）shl32 = 1
//
//      quot = floor((dividend << 32) / divisor)
//
//   等价于：
//
//      quot = floor(dividend * 2^32 / divisor)
//
//   这种模式非常适合计算 Q32 定点比例或者 32 bit 相位步长。
//
//   例如计算：
//
//      phase_step = 2^32 / 1024
//
//   输入：
//
//      dividend = 1
//      divisor  = 1024
//      shl32    = 1
//
//   输出：
//
//      quot = 4194304
//           = 0x00400000
//
// -----------------------------------------------------------------------------
// 为什么每个商 bit 要用 2 拍？
//
//   理论上，一轮除法可以直接做：
//
//      shifted >= divisor ?
//
//   但 shifted 宽度达到 66 bit。
//   如果同一拍完成：
//
//      66 bit 比较
//          ↓
//      65 bit 减法
//          ↓
//      更新余数和商
//
//   组合路径会比较长，不利于高频时序收敛。
//
//   因此这里人为拆成两拍：
//
//      RUN_HI：
//          先比较高 34 bit
//          把比较结果寄存下来
//
//      RUN_LO：
//          如果高位相等，再比较低 32 bit
//          然后完成减法并产生一个商 bit
//
//   因此：
//
//      1 个商 bit ≈ 3 个 clk
//      32 个商 bit ≈ 96 个 clk
//      只在 cfg_load / 扫描 FTW / 抖动 FTW，不在出波逐拍路径上
//
// -----------------------------------------------------------------------------
// 状态流程：
//
//                     start
//                       │
//                       ▼
//                  +----------+
//                  |   IDLE   |
//                  | 锁存参数 |
//                  +----+-----+
//                       │
//                       ▼
//                  +----------+
//                  |  RUN_HI  |
//                  | 高位比较 |
//                  +----+-----+
//                       │
//                       ▼
//                  +----------+
//                  |  RUN_GE  |
//                  | ge 与减法 |
//                  +----+-----+
//                       │
//                       ▼
//                  +----------+
//                  |  RUN_LO  |
//                  | 写入商位 |
//                  +----+-----+
//                       │
//                 i != 0│
//               +-------+
//               │
//               └──────────→ RUN_HI
//
//                       │ i == 0
//                       ▼
//                  +----------+
//                  |   FIN    |
//                  | 输出结果 |
//                  +----+-----+
//                       │
//                       ▼
//                     IDLE
//
// =============================================================================

module da_sig_div_u (

    input  wire        clk,          // FPGA 工作时钟
                                     // 所有状态机和寄存器都在 clk 上升沿更新

    input  wire        rst,          // 同步复位，高有效
                                     // 只有 clk 上升沿时 rst=1 才会执行复位

    input  wire        start,        // 启动脉冲
                                     // 只有在 IDLE 状态下 start=1 才接受新任务
                                     // 建议 start 只保持 1 个 clk

    input  wire        shl32,        // 运算模式选择
                                     //
                                     // shl32 = 0：
                                     //   dividend[31:0] / divisor
                                     //
                                     // shl32 = 1：
                                     //   (dividend << 32) / divisor
                                     //   即 dividend * 2^32 / divisor

    input  wire [47:0] dividend,     // 被除数
                                     //
                                     // shl32=0：
                                     //   只使用 dividend[31:0]
                                     //
                                     // shl32=1：
                                     //   使用完整 48 bit dividend
                                     //   初始直接装入 rem

    input  wire [63:0] divisor,      // 除数
                                     // 例如：
                                     //   N-1
                                     //   N_sample
                                     //   t_scan
                                     //   扫描点数等

    output reg  [31:0] quot,         // 最终 32 bit 商
                                     // 在 FIN 状态更新

    output reg         done          // 完成脉冲
                                     // FIN 状态拉高 1 个 clk
);


// =============================================================================
// 1. 状态机定义
// =============================================================================
//
// 使用 3 bit：
//
//   000：IDLE
//   001：RUN_HI
//   010：RUN_GE
//   011：RUN_LO
//   100：FIN
//
// =============================================================================

localparam [2:0] IDLE   = 3'd0;      // 空闲状态
                                     // 等待 start

localparam [2:0] RUN_HI = 3'd1;      // 每一轮除法的第 1 拍
                                     // 计算 shifted
                                     // 比较 shifted 和 divisor 的高 34 bit

localparam [2:0] RUN_GE = 3'd2;      // 每一轮除法的第 2 拍
                                     // 寄存 ge，并并行计算 sub=shifted-den

localparam [2:0] RUN_LO = 3'd3;      // 每一轮除法的第 3 拍
                                     // 按 ge 在 sub / shifted 中二选一
                                     // 更新 rem，写入 1 bit 商

localparam [2:0] FIN    = 3'd4;      // 除法完成
                                     // qacc → quot
                                     // done = 1


// =============================================================================
// 2. 内部寄存器
// =============================================================================

reg [2:0]  st;                       // 当前状态机状态
                                     // IDLE / RUN_HI / RUN_GE / RUN_LO / FIN


reg [5:0]  i;                        // 商位计数器
                                     //
                                     // 启动时：
                                     //   i = 31
                                     //
                                     // 每完成一个商 bit：
                                     //   i = i - 1
                                     //
                                     // 顺序：
                                     //   31 → 30 → ... → 1 → 0
                                     //
                                     // 一共执行 32 次


reg [64:0] rem;                      // 当前余数 remainder
                                     //
                                     // 它是整个恢复除法算法的核心寄存器。
                                     //
                                     // 每一轮先构造：
                                     //
                                     //   trial_rem = rem * 2 + next_bit
                                     //
                                     // 然后判断：
                                     //
                                     //   trial_rem >= divisor ?
                                     //
                                     // 如果成立：
                                     //
                                     //   rem = trial_rem - divisor
                                     //
                                     // 否则：
                                     //
                                     //   rem = trial_rem


reg [31:0] acc;                      // 被除数移位寄存器
                                     //
                                     // 只在 shl32=0 模式有实际作用。
                                     //
                                     // 初始化：
                                     //
                                     //   acc = dividend[31:0]
                                     //
                                     // 每一轮使用：
                                     //
                                     //   acc[31]
                                     //
                                     // 作为被除数下一 bit。
                                     //
                                     // 然后：
                                     //
                                     //   acc <= {acc[30:0], 1'b0}
                                     //
                                     // 相当于 acc 左移一位，
                                     // 下一轮继续取新的 acc[31]。


reg [31:0] qacc;                     // 商累加寄存器 quotient accumulator
                                     //
                                     // 每一轮确定一个商 bit。
                                     //
                                     // 如果够减：
                                     //
                                     //   qacc <= {qacc[30:0], 1'b1}
                                     //
                                     // 如果不够减：
                                     //
                                     //   qacc <= {qacc[30:0], 1'b0}
                                     //
                                     // 连续执行 32 次后形成完整 32 bit 商。


reg [63:0] den;                      // 锁存后的 divisor
                                     //
                                     // start 到来时：
                                     //
                                     //   den <= divisor
                                     //
                                     // 因为整个除法需要几十个时钟周期，
                                     // 运算过程中不能依赖外部 divisor 保持不变。
                                     //
                                     // 所以先锁存到 den，
                                     // 后续运算全部使用 den。


reg        mode32;                   // 锁存后的 shl32
                                     //
                                     // start 到来时：
                                     //
                                     //   mode32 <= shl32
                                     //
                                     // 防止运算过程中外部 shl32 变化。


reg [64:0] sh_r;                     // shifted remainder 寄存器
                                     //
                                     // RUN_HI 中把 shifted[64:0]
                                     // 锁存到这里。
                                     //
                                     // RUN_LO 下一拍使用 sh_r。
                                     //
                                     // 作用：
                                     //   在 RUN_HI / RUN_LO 之间插入寄存器，
                                     //   把长组合路径切成两段。


reg        hi_gt;                    // high greater than
                                     //
                                     // RUN_HI 中产生。
                                     //
                                     // 表示：
                                     //
                                     //   shifted[65:32]
                                     //        >
                                     //   den_ext[65:32]
                                     //
                                     // 如果 hi_gt=1，
                                     // 说明整体 shifted 已经确定 > divisor，
                                     // 不需要继续比较低 32 bit。


reg        hi_eq;                    // high equal
                                     //
                                     // 表示 shifted 和 divisor 的高 34 bit 相等。
                                     //
                                     // 如果 hi_eq=1，
                                     // RUN_GE 还需要进一步比较低 32 bit。

reg        ge_r;                     // RUN_GE 锁存的“够减”标志
                                     // RUN_LO 只做二选一，不再串比较

reg [64:0] sub_r;                    // RUN_GE 并行算出的 shifted-den
                                     // 与 ge 比较拆开，避免 10 级 CARRY 链


// =============================================================================
// 3. 组合逻辑：生成本轮“试探余数” shifted
// =============================================================================
//
// 每一轮恢复除法都要进行：
//
//      trial_rem = rem * 2 + next_bit
//
// 其中 next_bit 根据模式不同：
//
// -----------------------------------------------------------------------------
// shl32 = 0：普通 32 bit 除法
//
//      next_bit = acc[31]
//
// 所以：
//
//      shifted = {rem, acc[31]}
//
// 等价于：
//
//      shifted = rem * 2 + acc[31]
//
// 可以理解为：
//
//      “把被除数下一位拉到当前余数后面”
//
// -----------------------------------------------------------------------------
// shl32 = 1：计算 (dividend << 32) / divisor
//
// dividend << 32 表示：
//
//      dividend 后面补 32 个 0
//
// 因此每一轮拉下来的 bit 都是 0：
//
//      shifted = {rem, 1'b0}
//
// 即：
//
//      shifted = rem * 2
//
// =============================================================================

wire [65:0] shifted =
    mode32 ? {rem, 1'b0} :          // mode32=1：
                                     // rem 左移 1 bit，低位补 0
                                     // 对应 dividend << 32 的 32 个补零

             {rem, acc[31]};        // mode32=0：
                                     // rem 左移 1 bit，
                                     // 然后把被除数当前最高位 acc[31]
                                     // 拉进余数最低位


// =============================================================================
// 4. 除数扩展成 66 bit
// =============================================================================
//
// shifted 是 66 bit：
//
//      [65:0]
//
// den 是 64 bit：
//
//      [63:0]
//
// 为了方便比较，给 den 高位补两个 0：
//
//      den_ext = {00, den}
//
// =============================================================================

wire [65:0] den_ext = {2'd0, den};


// =============================================================================
// 5. 完整的 shifted >= divisor 判断
// =============================================================================
//
// 原本完全可以直接写：
//
//      shifted >= den_ext
//
// 但是这是一个 66 bit 宽比较器。
// 为了改善时序，这里拆成两部分。
//
// -----------------------------------------------------------------------------
// RUN_HI 已经比较高 34 bit：
//
//      shifted[65:32]
//      den_ext[65:32]
//
// 得到：
//
//      hi_gt：高位已经大于
//      hi_eq：高位相等
//
// -----------------------------------------------------------------------------
// 如果 hi_gt=1：
//
//      高位已经更大
//
// 那么整体一定：
//
//      shifted > divisor
//
// -----------------------------------------------------------------------------
// 如果 hi_eq=1：
//
//      高位相等
//
// 那么需要继续比较低 32 bit：
//
//      sh_r[31:0] >= den[31:0]
//
// -----------------------------------------------------------------------------
// 因此整体判断为：
//
//      高位大
//          OR
//      高位相等并且低位 >=
//
// =============================================================================

wire ge_lo =
    hi_gt ||                                        // 高 34 bit 已经更大
                                                    // 整体一定 >=

    (hi_eq && (sh_r[31:0] >= den[31:0]));          // 高位相等时
                                                    // 再比较低 32 bit


// =============================================================================
// 6. 最终“够不够减”的判断
// =============================================================================
//
// ge = 1：
//
//      当前试探余数 >= divisor
//
//      → 本商位 = 1
//      → rem 要减去 divisor
//
// ge = 0：
//
//      当前试探余数 < divisor
//
//      → 本商位 = 0
//      → rem 不减
//
// 同时加入除 0 保护：
//
//      den == 0 时永远不允许执行减法。
//
// =============================================================================

wire ge =
    (den != 64'd0) && ge_lo;


// =============================================================================
// 7. 主状态机
// =============================================================================
//
// 整个除法过程：
//
//   start
//      │
//      ▼
//   IDLE
//      │ 锁存 divisor / shl32 / dividend
//      ▼
//   RUN_HI
//      │ 计算 shifted
//      │ 比较高 34 bit
//      ▼
//   RUN_LO
//      │ 完成整体比较
//      │ 减法或保持
//      │ 写入 1 bit 商
//      │
//      ├── i != 0 ──→ RUN_HI
//      │
//      └── i == 0 ──→ FIN
//
//   FIN
//      │ quot <= qacc
//      │ done <= 1
//      ▼
//   IDLE
//
// =============================================================================

always @(posedge clk) begin

    // =========================================================================
    // 同步复位
    // =========================================================================
    //
    // 注意：
    //
    //   always @(posedge clk)
    //
    // 中检查 rst，
    // 所以这是同步复位。
    //
    // 只有在 clk 上升沿到来的时候，
    // rst=1 才会真正把寄存器清零。
    //
    // =========================================================================

    if (rst) begin

        st     <= IDLE;                  // 状态机回到空闲状态

        done   <= 1'b0;                  // 完成脉冲清零

        quot   <= 32'd0;                 // 输出商清零

        i      <= 6'd0;                  // 商位计数器清零

        rem    <= 65'd0;                 // 当前余数清零

        acc    <= 32'd0;                 // 被除数移位寄存器清零

        qacc   <= 32'd0;                 // 商累加寄存器清零

        den    <= 64'd0;                 // 锁存除数清零

        mode32 <= 1'b0;                  // 默认普通低 32 bit 除法模式

        sh_r   <= 65'd0;                 // RUN_HI 中间结果清零

        hi_gt  <= 1'b0;                  // 高位大于标志清零

        hi_eq  <= 1'b0;                  // 高位相等标志清零

        ge_r   <= 1'b0;                  // 够减标志清零

        sub_r  <= 65'd0;                 // 预减结果清零


    end else begin

        // =====================================================================
        // done 默认每拍拉低
        // =====================================================================
        //
        // 只有进入 FIN 状态时，
        //
        //      done <= 1'b1;
        //
        // 因此 done 只会保持一个时钟周期：
        //
        //      ____|‾|____
        //
        // =====================================================================

        done <= 1'b0;


        // =====================================================================
        // 根据当前状态执行对应逻辑
        // =====================================================================

        case (st)


            // =================================================================
            // IDLE：等待 start，并初始化一次新的除法
            // =================================================================

            IDLE: begin

                // -------------------------------------------------------------
                // 只有 IDLE 状态下 start=1 才接受新任务
                // -------------------------------------------------------------

                if (start) begin

                    // ---------------------------------------------------------
                    // 锁存除数
                    // ---------------------------------------------------------
                    //
                    // 运算会持续约 96 个 clk，
                    // 所以后续不直接使用外部 divisor，
                    // 而使用内部寄存器 den。
                    //
                    // ---------------------------------------------------------

                    den <= divisor;


                    // ---------------------------------------------------------
                    // 锁存 shl32 模式
                    // ---------------------------------------------------------

                    mode32 <= shl32;


                    // ---------------------------------------------------------
                    // 新一次除法开始，商从 0 开始
                    // ---------------------------------------------------------

                    qacc <= 32'd0;


                    // ---------------------------------------------------------
                    // 需要生成 32 个商 bit
                    //
                    // i：
                    //
                    //   31 → 30 → ... → 1 → 0
                    //
                    // 一共正好 32 次。
                    // ---------------------------------------------------------

                    i <= 6'd31;


                    // ---------------------------------------------------------
                    // 根据 shl32 选择两种不同的初始化方式
                    // ---------------------------------------------------------

                    if (shl32) begin

                        // =====================================================
                        // shl32 = 1
                        //
                        // 计算：
                        //
                        //      (dividend << 32) / divisor
                        //
                        // 可以把 dividend << 32 理解为：
                        //
                        //      dividend + 后面 32 个 0
                        //
                        // 所以：
                        //
                        //   1. dividend 先直接装入 rem
                        //   2. 后面连续 32 轮，每轮向 rem 后面补一个 0
                        //
                        // 最终等价于处理：
                        //
                        //      dividend * 2^32
                        //
                        // =====================================================

                        rem <= {17'd0, dividend};
                                            // dividend 是 48 bit
                                            // rem 是 65 bit
                                            //
                                            // 17 + 48 = 65
                                            //
                                            // 所以前面补 17 个 0，
                                            // 把完整 dividend 零扩展到 65 bit


                        acc <= 32'd0;        // 该模式不需要 acc 提供 bit
                                            //
                                            // 后续每一轮直接补 0：
                                            //
                                            //   shifted = {rem,1'b0}


                    end else begin

                        // =====================================================
                        // shl32 = 0
                        //
                        // 普通除法：
                        //
                        //      dividend[31:0] / divisor
                        //
                        // 二进制竖式除法从：
                        //
                        //      rem = 0
                        //
                        // 开始。
                        //
                        // dividend[31:0] 放入 acc，
                        // 后续每轮从 acc[31] 取一位。
                        // =====================================================

                        rem <= 65'd0;        // 初始余数为 0

                        acc <= dividend[31:0];
                                            // 保存低 32 bit 被除数
                                            //
                                            // 后续：
                                            //
                                            //   acc[31]
                                            //
                                            // 会一位一位被拉到 rem 中

                    end


                    // ---------------------------------------------------------
                    // 判断除数是否为 0
                    // ---------------------------------------------------------
                    //
                    // 注意这里使用的是 divisor，
                    // 而不是 den。
                    //
                    // 原因：
                    //
                    //      den <= divisor
                    //
                    // 是非阻塞赋值，
                    // 当前这个时钟沿内部 den 还是旧值。
                    //
                    // 所以必须直接判断当前输入 divisor。
                    //
                    // ---------------------------------------------------------

                    st <= (divisor == 64'd0) ?
                          FIN :              // divisor=0：
                                             // 不执行除法
                                             // 直接进入 FIN
                                             // 最终 quot 输出 0

                          RUN_HI;            // divisor!=0：
                                             // 开始第一个商 bit 的计算

                end

            end


            // =================================================================
            // RUN_HI：每个商 bit 的第 1 拍
            // =================================================================
            //
            // 本拍主要做两件事情：
            //
            // 1. 生成并保存 shifted
            //
            //      普通模式：
            //
            //          shifted = {rem,acc[31]}
            //
            //      shl32 模式：
            //
            //          shifted = {rem,1'b0}
            //
            // 2. 只比较 shifted / divisor 的高 34 bit
            //
            // 这样避免在一个 clk 内完成完整 66 bit 比较 + 65 bit 减法。
            //
            // =================================================================

            RUN_HI: begin

                // -------------------------------------------------------------
                // 保存试探余数的低 65 bit
                // -------------------------------------------------------------
                //
                // shifted 是 66 bit：
                //
                //      [65:0]
                //
                // sh_r 保存：
                //
                //      [64:0]
                //
                // 最高位 shifted[65]
                // 已经会参与下面高 34 bit 的比较，
                // 所以不需要单独保存进 sh_r。
                //
                // -------------------------------------------------------------

                sh_r <= shifted[64:0];


                // -------------------------------------------------------------
                // 比较高 34 bit
                //
                // [65:32]：
                //
                //      65 - 32 + 1 = 34 bit
                //
                // 如果 shifted 高位已经更大，
                // 那么整体一定 shifted > divisor。
                //
                // -------------------------------------------------------------

                hi_gt <=
                    (shifted[65:32] > den_ext[65:32]);


                // -------------------------------------------------------------
                // 如果高 34 bit 完全相等，
                // 下一拍 RUN_LO 还需要比较低 32 bit。
                // -------------------------------------------------------------

                hi_eq <=
                    (shifted[65:32] == den_ext[65:32]);


                // -------------------------------------------------------------
                // 下一拍进入 RUN_GE：比较与减法并行寄存
                // -------------------------------------------------------------

                st <= RUN_GE;

            end


            // =================================================================
            // RUN_GE：每个商 bit 的第 2 拍
            // =================================================================
            //
            // 只寄存 ge，并无条件计算 sub = shifted - den。
            // 比较链不再串进 65 bit 减法，368 MHz 下拆成两段。
            //
            // =================================================================

            RUN_GE: begin

                ge_r <= ge;              // 32 bit 低位比较 + hi_gt/hi_eq

                sub_r <= sh_r - den_ext[64:0];
                                         // 无条件预减；ge=0 时 RUN_LO 不用它

                st <= RUN_LO;

            end


            // =================================================================
            // RUN_LO：每个商 bit 的第 2 拍
            // =================================================================
            //
            // 这里根据 ge 最终决定：
            //
            //      当前试探余数是否 >= divisor
            //
            // 如果 >=：
            //
            //      rem  = shifted - divisor
            //      商位 = 1
            //
            // 如果 <：
            //
            //      rem  = shifted
            //      商位 = 0
            //
            // =================================================================

            RUN_LO: begin


                // -------------------------------------------------------------
                // ge=1：当前余数够减一次 divisor
                // -------------------------------------------------------------

                if (ge_r) begin

                    // ---------------------------------------------------------
                    // 恢复除法：
                    //
                    //      rem_new = trial_rem - divisor
                    //
                    // 减法和 ge 已在 RUN_GE 寄存，本拍只选结果。
                    //
                    // ---------------------------------------------------------

                    rem <= sub_r;


                    // ---------------------------------------------------------
                    // 当前商 bit = 1
                    //
                    // qacc 整体左移一位，
                    // 然后最低位写 1。
                    //
                    // 等价于：
                    //
                    //      qacc_new = qacc * 2 + 1
                    //
                    // ---------------------------------------------------------

                    qacc <= {qacc[30:0], 1'b1};


                end else begin

                    // ---------------------------------------------------------
                    // ge=0：
                    //
                    // 当前试探余数 < divisor
                    //
                    // 不够减。
                    //
                    // ---------------------------------------------------------

                    rem <= sh_r;           // 不减 divisor
                                           // trial_rem 直接成为新的 rem


                    // ---------------------------------------------------------
                    // 当前商 bit = 0
                    //
                    // qacc 左移一位，
                    // 最低位补 0。
                    //
                    // 等价于：
                    //
                    //      qacc_new = qacc * 2
                    //
                    // ---------------------------------------------------------

                    qacc <= {qacc[30:0], 1'b0};

                end


                // -------------------------------------------------------------
                // 被除数 acc 左移一位
                // -------------------------------------------------------------
                //
                // 例如：
                //
                //      acc = 110100...
                //
                // 本轮使用 acc[31] = 1 后：
                //
                //      acc <= 101000...
                //
                // 下一轮 acc[31] 就是原来的下一 bit。
                //
                // shl32=1 时 acc 本来就是 0，
                // 所以这一句不会产生实际影响。
                //
                // -------------------------------------------------------------

                acc <= {acc[30:0], 1'b0};


                // -------------------------------------------------------------
                // 判断 32 个商 bit 是否已经全部完成
                // -------------------------------------------------------------

                if (i == 6'd0) begin

                    // ---------------------------------------------------------
                    // 当前已经完成最后一个商 bit。
                    //
                    // 下一拍进入 FIN。
                    //
                    // 注意：
                    //
                    // qacc <= ...
                    //
                    // 和：
                    //
                    // st <= FIN
                    //
                    // 都是非阻塞赋值。
                    //
                    // 当前时钟沿结束后 qacc 会更新为最终商，
                    // 下一拍 FIN 看到的就是完整 qacc。
                    //
                    // ---------------------------------------------------------

                    st <= FIN;


                end else begin

                    // ---------------------------------------------------------
                    // 还没完成全部 32 bit
                    //
                    // 位计数器减 1
                    // ---------------------------------------------------------

                    i <= i - 6'd1;


                    // ---------------------------------------------------------
                    // 回 RUN_HI，
                    // 开始计算下一个商 bit
                    // ---------------------------------------------------------

                    st <= RUN_HI;

                end

            end


            // =================================================================
            // FIN：输出最终结果
            // =================================================================

            FIN: begin

                // -------------------------------------------------------------
                // 如果 divisor=0：
                //
                //      quot = 0
                //
                // 这是工程上的保护规定，
                // 并不是数学意义上的除 0 结果。
                //
                // 正常情况：
                //
                //      quot = qacc
                //
                // -------------------------------------------------------------

                quot <= (den == 64'd0) ?
                        32'd0 :
                        qacc;


                // -------------------------------------------------------------
                // 输出 1 个 clk 的完成脉冲
                //
                // 上层模块可以通过 done 判断：
                //
                //      除法结果已经产生
                //
                // -------------------------------------------------------------

                done <= 1'b1;


                // -------------------------------------------------------------
                // 本次除法结束，
                // 回到 IDLE 等待下一次 start
                // -------------------------------------------------------------

                st <= IDLE;

            end


            // =================================================================
            // 异常状态保护
            // =================================================================
            //
            // st 是 3 bit。未使用编码回到 IDLE。
            //
            // default 主要是防止仿真 X、异常状态等情况。
            //
            // =================================================================

            default: begin

                st <= IDLE;

            end

        endcase

    end

end

