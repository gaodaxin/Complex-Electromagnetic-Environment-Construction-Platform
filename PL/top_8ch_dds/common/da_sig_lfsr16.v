// SOURCE: RFSOC_DEMO.srcs/sources_1/new/da_lfm/da_sig_lfsr16.v
// 功能：产生 16 bit 伪随机序列，为随机 PRI、跳频或码元提供随机源；零种子替换为非零值。
// ============================================================================
`timescale 1ns / 1ps

// =============================================================================
// 模块: da_sig_lfsr16
// 功能: 16 bit 最大长度伪随机序列发生器，供 PRI 抖动、随机跳频和随机码元使用。
// 说明: seed=0 时使用非零后备种子，防止 LFSR 永久锁死在全零状态。
// =============================================================================

module da_sig_lfsr16 (

    input  wire        clk,              // FPGA 工作时钟
    input  wire        rst_sync,         // 同步复位，高有效；复位时装入 seed
    input  wire [15:0] seed,             // 复位初值；全 0 非法，会改成 16'hBEEF
    output reg  [15:0] lfsr              // 当前 16 bit 伪随机字
);

// 多项式 x^16+x^14+x^13+x^11+1
// 反馈 bit = q15 ^ q13 ^ q12 ^ q10
// 每拍左移 1 bit，给 PRI 抖动/滑变、捷变随机 hop 共用

always @(posedge clk) begin

    if (rst_sync)
        lfsr <= (seed == 16'd0) ?
                16'hBEEF :               // 全 0 会锁死 LFSR，改用固定种子
                seed;                    // 正常情况使用调用方给的种子

    else
        lfsr <= {lfsr[14:0],             // 低 15 bit 左移
                 lfsr[15] ^ lfsr[13] ^   // 最高 bit 与抽头异或后送进 LSB
                 lfsr[12] ^ lfsr[10]};

end

endmodule
